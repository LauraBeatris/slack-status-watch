// Usage: swift Scripts/generate-emoji-table.swift path/to/emoji.json > Packages/SlackStatusKit/Sources/SlackStatusKit/SlackEmojiTable.swift
// emoji.json comes from https://github.com/iamcal/emoji-data (MIT), the dataset Slack's picker uses

import Foundation

struct Entry: Decodable {
  let unified: String
  let short_names: [String]
}

let path = CommandLine.arguments[1]
let data = try Data(contentsOf: URL(fileURLWithPath: path))
let entries = try JSONDecoder().decode([Entry].self, from: data)

func character(_ unified: String) -> String {
  String(String.UnicodeScalarView(unified.split(separator: "-").map { Unicode.Scalar(UInt32($0, radix: 16)!)! }))
}

var lines: [String] = []
for entry in entries.sorted(by: { $0.short_names[0] < $1.short_names[0] }) {
  let value = character(entry.unified).unicodeScalars.map { String(format: "\\u{%X}", $0.value) }.joined()
  for name in entry.short_names {
    lines.append("  \"\(name)\": \"\(value)\",")
  }
}

print("// Generated by Scripts/generate-emoji-table.swift from emoji-data. Do not edit by hand")
print("")
print("let slackEmojiTable: [String: String] = [")
print(lines.joined(separator: "\n"))
print("]")
